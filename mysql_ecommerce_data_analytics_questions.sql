/* Q12. Order Contribution to Customer Revenue
For every order, calculate:
- order value
- customer's total revenue
- percentage of customer revenue contributed by that order
Use a window function to calculate the customer total. */

WITH order_values AS (
    SELECT o.order_id, o.customer_id, o.order_date,
        SUM(po.quantity * po.unit_price) AS order_value
    FROM orders o
    JOIN product_orders po
        ON o.order_id = po.order_id
    GROUP BY o.order_id, o.customer_id, o.order_date
) 
SELECT order_id, customer_id, order_date,
    ROUND(order_value, 2) AS order_value,
    ROUND( SUM(order_value) OVER (
            PARTITION BY customer_id), 2 ) AS customer_total_revenue,
    ROUND( order_value * 100.0 /SUM(order_value) OVER (PARTITION BY customer_id), 2) 
    AS revenue_contribution_percentage
FROM order_values
ORDER BY customer_id, order_date, order_id;

