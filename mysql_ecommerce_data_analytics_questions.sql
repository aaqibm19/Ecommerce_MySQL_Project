ORDER BY total_revenue DESC;

/* Q17. Top 5 Customers in Each Month
Using a CTE and ROW_NUMBER(), find the top 5 customers
by revenue in every month. */

WITH customer_monthly_revenue AS (
    SELECT
        o.customer_id, DATE_FORMAT(o.order_date, '%Y-%m') AS order_month,
        SUM(po.quantity * po.unit_price) AS monthly_revenue
