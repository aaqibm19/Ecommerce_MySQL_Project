/* Q1. Customer Revenue Analysis
Find every customer who has placed at least one order.
Show:
- customer_id
- customer name
- number of orders
- total quantity purchased
- total revenue
Sort by total revenue from highest to lowest. */

select c.customer_id, concat(c.first_name," ",c.last_name) as FullName, sum(po.quantity) as total_quantity_purchased, 
sum(po.quantity*unit_price) as total_revenue
from customers c 
join orders o 
on c.customer_id = o.customer_id
join product_orders po
on o.order_id = po.order_id
group by c.customer_id, c.first_name, c.last_name
order by c.customer_id;

