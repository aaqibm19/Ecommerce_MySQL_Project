/* Q18. Customers With Increasing Order Activity
Find customers whose last order value is greater than their
first order value.

Return:
- customer_id
- first_order_value
- last_order_value
- increase_amount */
WITH order_values AS (
    SELECT o.order_id, o.customer_id, o.order_date,
        SUM(po.quantity * po.unit_price) AS order_value
    FROM orders o
    JOIN product_orders po
        ON o.order_id = po.order_id
    GROUP BY o.order_id, o.customer_id, o.order_date
),
customer_orders AS (
    SELECT customer_id,
        FIRST_VALUE(order_value) OVER (
            PARTITION BY customer_id
            ORDER BY order_date, order_id
        ) AS first_order_value,
        LAST_VALUE(order_value) OVER (
            PARTITION BY customer_id
            ORDER BY order_date, order_id
            ROWS BETWEEN UNBOUNDED PRECEDING
            AND UNBOUNDED FOLLOWING
        ) AS last_order_value
    FROM order_values
)

SELECT DISTINCT
    customer_id, first_order_value, last_order_value
FROM customer_orders
WHERE last_order_value > first_order_value
ORDER BY customer_id;

/* Q19. Orders Above Monthly Average
Using CTEs, calculate each order's value and the average
order value for its month.
Return orders whose value is greater than their month's
average order value. */

-- Step 1: Calculate the total value of each order
WITH order_values AS (
    SELECT o.order_id, o.order_date,
        DATE_FORMAT(o.order_date, '%Y-%m') AS order_month,
        ROUND(SUM(po.quantity * po.unit_price), 2) AS order_value
    FROM orders o
    JOIN product_orders po
        ON o.order_id = po.order_id
    GROUP BY o.order_id, o.order_date
),

-- Step 2: Calculate average ORDER value for each month
monthly_averages AS (
    SELECT order_month,
        ROUND(AVG(order_value), 2) AS monthly_avg_order_value
    FROM order_values
    GROUP BY order_month
)
-- Step 3: Compare each order against its month's average
SELECT ov.order_id, ov.order_date, ov.order_month, ov.order_value, ma.monthly_avg_order_value
FROM order_values ov
JOIN monthly_averages ma
    ON ov.order_month = ma.order_month
WHERE ov.order_value > ma.monthly_avg_order_value
ORDER BY ov.order_month, ov.order_id;

/* Q20. Customer Retention / Repeat Purchase Analysis
Using CTEs, find customers who placed at least 2 orders.
Show:
- customer_id
- first_order_date
- last_order_date
- total_orders
- days_between_first_and_last_order */

WITH customer_orders AS (
    SELECT customer_id,
        MIN(order_date) AS first_order_date,
        MAX(order_date) AS last_order_date,
        COUNT(order_id) AS total_orders
    FROM orders
    GROUP BY customer_id
)

SELECT
    customer_id,
    first_order_date,
    last_order_date,
    total_orders,
    DATEDIFF(last_order_date, first_order_date) AS days_between_first_and_last_order
FROM customer_orders
WHERE total_orders >= 2
ORDER BY customer_id;

