/* Q14. Monthly Revenue Growth
Calculate monthly revenue and compare each month with the
previous month using LAG().
Show:
- month
- monthly_revenue
- previous_month_revenue
- revenue_change
- growth_percentage */

with monthWise_revenue as (select date_format(o.order_date,'%Y-%m') as month,
round(sum(po.quantity * po.unit_price),2) as monthly_revenue
from orders o
join product_orders po
on o.order_id = po.order_id
group by month),
preMonthRev as (select month, monthly_revenue,
lag(monthly_revenue) over(order by month) as previous_month_revenue
from monthWise_revenue)

select month, monthly_revenue, previous_month_revenue,
ROUND(monthly_revenue - previous_month_revenue, 2) AS revenue_change,
round(((monthly_revenue- previous_month_revenue)/ NULLIF(previous_month_revenue,0))* 100,2) as growth_percentage
from preMonthRev;

/* Q15. Customer Purchase Segmentation
Using a CTE, calculate each customer's:
- total orders
- total revenue

Then classify customers as:
- High Value: revenue >= 1000
- Medium Value: revenue >= 500 and < 1000
- Low Value: revenue < 500
Return customer_id, customer_name, orders, revenue, segment. */

with customer_revenue as (select c.customer_id, concat(c.first_name,' ',c.last_name) as customer_name,
