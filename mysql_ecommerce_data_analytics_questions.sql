     else 'Low Value' end) as segment
from customer_revenue;
/* Q16. Product Type Performance
Using CTEs, calculate revenue for every product and then
summarize the results by product_type.
Show:
- product_type
- products_sold
- total_quantity
- total_revenue
- average_product_revenue */
WITH product_revenue AS (
    SELECT
        p.product_id,
        p.product_type,
        SUM(po.quantity) AS total_quantity,
        SUM(po.quantity * po.unit_price) AS product_revenue
    FROM products p
    JOIN product_orders po
        ON p.product_id = po.product_id
    GROUP BY p.product_id, p.product_type
)

SELECT
    product_type,
    COUNT(product_id) AS products_sold,
    SUM(total_quantity) AS total_quantity,
